def _ok(data: Any) -> httpx.Response:
    return httpx.Response(200, json={"success": True, "data": data, "error": None})


class MiLLMStub:
    """miLLM as 038 S1 serves it, at the HTTP layer. `armed=False` is an unarmed deployment: the
    chat body is the pre-038 body, with no `millm_probe_verdicts` key at all."""

    def __init__(self, *, armed: bool = True, chat_status: int = 200, mixed: bool = False,
                 chat_unreachable: bool = False):
        self.armed = armed
        self.chat_status = chat_status
        #: `mixed`: the body also carries the results that said NOTHING (skipped / failed,
        #: `verdict: null`) — generated by miLLM's builder, never hand-written.
        self.mixed = mixed
        #: `chat_unreachable`: the gate passes, then the chat POST fails at the transport —
        #: `send()` answers `{"unavailable": "millm"}` and that shape reaches the lift.
        self.chat_unreachable = chat_unreachable
        self.requests: list[dict[str, Any]] = []
        self.health_probes = 0

    def chat_body(self) -> dict[str, Any]:
        body = {
            "id": "chatcmpl-038s3m", "object": "chat.completion", "created": 1792854000,
            "model": "tiny",
            "choices": [{"index": 0, "message": {"role": "assistant", "content": "hello"},
                         "finish_reason": "stop", "logprobs": None}],
            "usage": {"prompt_tokens": 5, "completion_tokens": 1, "total_tokens": 6},
        }
        if self.armed:
            body["millm_probe_verdicts"] = copy.deepcopy(FIXTURE["millm_probe_verdicts"])
            if self.mixed:
                body["millm_probe_verdicts"] += copy.deepcopy(
                    FIXTURE["millm_probe_verdicts_not_completed"])
        return body

    def __call__(self, request: httpx.Request) -> httpx.Response:
        method, path = request.method, request.url.path
        if (method, path) == ("GET", "/api/health"):
            self.health_probes += 1
            return httpx.Response(200, json={"status": "healthy"})
        sent = {
            "method": method, "path": path,
            "query": dict(parse_qsl(request.url.query.decode())),
            "json": json.loads(request.content) if request.content else None,
            "headers": {k: v for k, v in request.headers.items() if k.startswith("x-millm-")},
        }
        self.requests.append(sent)
        if (method, path) == ("POST", "/v1/chat/completions"):
            if self.chat_unreachable:
                raise httpx.ConnectError("connection refused", request=request)
            if self.chat_status == 409:
                return httpx.Response(409, json={"error": {
                    "message": "model m is not resident", "type": "invalid_request_error",
                    "param": "model", "code": "model_not_resident"}})
            return httpx.Response(200, json=self.chat_body(),
                                  headers={"X-miLLM-Steering": "none"})
        if (method, path) == ("POST", "/api/probes/score"):
            data = {"model": {"name": "tiny"}, "probes": [], "skipped": [],
                    "results": [{"index": 0, "token_ids": None, "error": None,
                                 "verdicts": copy.deepcopy(FIXTURE["score_verdicts"])}]}
            if "export_results" in (sent["json"] or {}):
                data["export"] = {"requested": sent["json"]["export_results"],
                                  "permitted": False, "records_queued": 0}
            return _ok(data)
        if (method, path) == ("GET", "/api/probes/events"):
            rows = copy.deepcopy(FIXTURE["event_rows"])
            for key in ("result_id", "trace_id", "probe_id", "request_id"):
                if key in sent["query"]:
                    rows = [r for r in rows if r.get(key) == sent["query"][key]]
            return _ok(rows[: int(sent["query"].get("limit", 100))])
        if method == "GET" and path.startswith("/api/probes/events/"):
            event_id = int(path.rsplit("/", 1)[1])
            row = next(r for r in FIXTURE["event_rows"] if r["id"] == event_id)
            return _ok({**copy.deepcopy(row), "context_text": "<user text>",
                        "context_token_ids": [1, 2, 3]})
        if (method, path) == ("GET", "/api/health/detailed"):
            return httpx.Response(200, json={"status": "healthy", "model": None,
                                             "telemetry": copy.deepcopy(TELEMETRY)})
        return httpx.Response(404, json={"detail": "Not Found"})


def _server(stub: MiLLMStub, monkeypatch):
    """The REAL `build_server()`; every httpx client it makes talks to `stub`."""
    from src.mcp_server.config import MCPSettings
    from src.mcp_server.products import PRODUCTS
    from src.mcp_server.server import build_server

    real = httpx.AsyncClient

    class StubbedAsyncClient(real):
        def __init__(self, *args, **kwargs):
            kwargs["transport"] = httpx.MockTransport(stub)
            super().__init__(*args, **kwargs)

    monkeypatch.setattr(httpx, "AsyncClient", StubbedAsyncClient)
    for spec in PRODUCTS:
        monkeypatch.setenv(spec.url_env, f"http://{spec.name}.test")
    mcp, _ = build_server(MCPSettings(tool_categories=CATEGORIES, allow_anonymous=True),
                          stdio=True)
    return mcp


def _call(mcp, name: str, args: dict[str, Any]) -> Any:
    result = asyncio.run(mcp.call_tool(name, args))
    assert not result.is_error, result
    structured = result.structured_content
    if isinstance(structured, dict) and set(structured) == {"result"}:
        return structured["result"]
    return structured if structured is not None else json.loads(result.content[0].text)


def _one_call(stub: MiLLMStub) -> dict[str, Any]:
    assert len(stub.requests) == 1, f"expected exactly one REST call, got {stub.requests}"
    return stub.requests[0]


