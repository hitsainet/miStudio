@pytest.mark.parametrize("tool,extra_body", [
    ("millm_generate", {"max_tokens": 8}),
    ("millm_score_chat", {"logprobs": True, "max_tokens": 1, "temperature": 0}),
])
class TestTheLift:
    def _args(self, tool):
        return dict(CHAT, max_tokens=8) if tool == "millm_generate" else dict(CHAT)

    def test_armed_every_probe_x_window_reaches_the_top_level_unchanged(
            self, tool, extra_body, monkeypatch):
        stub = MiLLMStub(armed=True)
        result = _call(_server(stub, monkeypatch), tool, self._args(tool))

        sent = _one_call(stub)
        assert (sent["method"], sent["path"]) == ("POST", "/v1/chat/completions")
        assert sent["json"] == {**CHAT, **extra_body}
        assert sent["headers"] == SENT
        assert stub.health_probes == 1

        expected = FIXTURE["millm_probe_verdicts"]
        assert result["millm_probe_verdicts"] == expected, "the lift changed or dropped the list"
        # Left in place (D38.47): the body is what an OpenAI client reads, byte for byte.
        assert result["result"] == stub.chat_body()
        assert {(v["probe_id"], v["window"]) for v in result["millm_probe_verdicts"]} == {
            ("pr_0123456789ab", "response"), ("pr_0123456789ab", "prompt")}
        for got, want in zip(result["millm_probe_verdicts"], expected, strict=True):
            for field in CONTRACT_FIELDS:
                assert got[field] == want[field], field

    def test_unarmed_the_list_is_empty_and_the_body_untouched(self, tool, extra_body,
                                                               monkeypatch):
        stub = MiLLMStub(armed=False)
        result = _call(_server(stub, monkeypatch), tool, self._args(tool))
        _one_call(stub)
        assert result["millm_probe_verdicts"] == []
        assert "millm_probe_verdicts" not in result["result"], "an unarmed body must not change"
        assert result["result"] == stub.chat_body()

    def test_results_that_said_nothing_are_lifted_too_in_order(self, tool, extra_body,
                                                               monkeypatch):
        """A skipped or failed result is part of the answer: dropping it would read as "that
        probe was not armed" (or, filtered to verdicts, as a cleaner run than happened)."""
        stub = MiLLMStub(mixed=True)
        result = _call(_server(stub, monkeypatch), tool, self._args(tool))
        _one_call(stub)
        expected = (FIXTURE["millm_probe_verdicts"]
                    + FIXTURE["millm_probe_verdicts_not_completed"])
        assert result["millm_probe_verdicts"] == expected
        assert result["result"]["millm_probe_verdicts"] == expected
        assert [v["outcome"] for v in result["millm_probe_verdicts"]] == [
            "completed", "completed", "skipped", "failed"]

    def test_a_post_gate_unavailable_gets_NO_verdict_list(self, tool, extra_body, monkeypatch):
        """The gate passed, then the call failed at the transport: `send()` answers
        `unavailable`, which reaches the lift. `[]` beside it would read as "nothing armed"."""
        stub = MiLLMStub(chat_unreachable=True)
        result = _call(_server(stub, monkeypatch), tool, self._args(tool))
        _one_call(stub)
        assert result["unavailable"] == "millm"
        assert "millm_probe_verdicts" not in result

    def test_a_refusal_gets_NO_verdict_list(self, tool, extra_body, monkeypatch):
        """`[]` beside a refusal would read as "scored, nothing armed"."""
        stub = MiLLMStub(chat_status=409)
        result = _call(_server(stub, monkeypatch), tool, self._args(tool))
        _one_call(stub)
        assert result["refused"] == "model_not_resident"
        assert "millm_probe_verdicts" not in result


