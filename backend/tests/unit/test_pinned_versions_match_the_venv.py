"""The image installs exactly what the tests run: D31, "ship what is tested".

2026-10-17: `requirements.txt` said `mcp>=1.9.0,<2` beside `uvicorn==0.24.0.post1`. mcp 1.28.1
requires uvicorn>=0.31.1, so the image's resolver fell back to mcp 1.12.4 (read from both the
mistudio-backend and mistudio-mcp pods) while every MCP test ran 1.28.1. A clean-venv dry run
then showed 24 more runtime packages resolving to versions no test had run (fastapi 0.143.3,
starlette 1.8.0, weasel 1.0.0, ...), because ranges and transitives float at build time.

Now `requirements.txt` pins what it names and `constraints.txt` (generated by
`scripts/lock_constraints.py`) pins every other package of the resolved closure; the image and
CI install `-r requirements.txt -c constraints.txt`. Everything below is DERIVED from those two
files and from the installed distributions — there is no hand list of package names except the
dev-only exceptions, which are the one thing that cannot be derived.
"""

from __future__ import annotations

import importlib.metadata as md
import importlib.util
import re
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.version import Version

BACKEND = Path(__file__).resolve().parents[2]
REQUIREMENTS = BACKEND / "requirements.txt"
CONSTRAINTS = BACKEND / "constraints.txt"
PYPROJECT = BACKEND / "pyproject.toml"

#: Roots CI's CPU runner deliberately does not install (backend-tests.yml greps them out).
CI_ABSENT = frozenset({"triton", "bitsandbytes"})

#: In the dev venv but NOT in the image, and not imported by the backend: the poetry tree
#: removed from requirements.txt on 2026-10-08, a Pillow nothing in src/ imports, the spaCy
#: model the Dockerfile downloads separately, and the installer's own tooling.
DEV_ONLY = frozenset({
    "build", "cachecontrol", "cleo", "crashtest", "distlib", "dulwich", "fastjsonschema",
    "findpython", "installer", "jaraco-classes", "jaraco-context", "jaraco-functools", "jeepney",
    "keyring", "more-itertools", "msgpack", "pbs-installer", "pkginfo", "poetry", "poetry-core",
    "pyproject-hooks", "rapidfuzz", "requests-toolbelt", "secretstorage", "tomlkit",
    "trove-classifiers", "virtualenv",
    "pillow", "en-core-web-sm",
    "pip", "setuptools", "wheel",
})


def _lock():
    spec = importlib.util.spec_from_file_location("lock_constraints", BACKEND / "scripts" / "lock_constraints.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


lock = _lock()


def _pins(path: Path) -> dict[str, str]:
    return lock.exact_pins(lock.requirement_lines(path))


def _installed(name: str):
    try:
        return md.version(name)
    except md.PackageNotFoundError:
        return None


def _same(installed: str, pinned: str) -> bool:
    # `2.9.1+cpu` (CI's CPU torch) is the pinned 2.9.1; the local label is the build, not the version.
    return Version(installed).public == Version(pinned).public


def test_constraints_pin_only_exact_versions():
    reqs = lock.requirement_lines(CONSTRAINTS)
    assert reqs, "constraints.txt is empty"
    loose = [str(r) for r in reqs if lock.normalise(r.name) not in _pins(CONSTRAINTS)]
    assert not loose, f"constraints must be exact (==): {loose}"


def test_no_package_is_pinned_twice():
    both = set(_pins(REQUIREMENTS)) & set(_pins(CONSTRAINTS))
    assert not both, f"pinned in requirements.txt AND constraints.txt: {sorted(both)}"


def test_every_pinned_version_is_the_installed_version():
    """Every `==` in requirements.txt and constraints.txt, against the venv the suite runs in."""
    pins = {**_pins(CONSTRAINTS), **_pins(REQUIREMENTS)}
    drift = {}
    for name, pinned in pins.items():
        installed = _installed(name)
        if installed is None:
            continue  # not in this venv's closure (e.g. CUDA wheels on CI); coverage is checked below
        if not _same(installed, pinned):
            drift[name] = {"pinned": pinned, "installed": installed}
    assert not drift, f"the image would install versions the tests did not run: {drift}"


def test_every_package_the_closure_installs_is_pinned():
    """A new transitive dependency must be locked before it ships, or the image picks its version."""
    resolved = lock.closure(lock.requirement_lines(REQUIREMENTS), absent_ok=CI_ABSENT)
    pinned = {**_pins(CONSTRAINTS), **_pins(REQUIREMENTS)}
    unpinned = sorted(set(resolved) - set(pinned))
    assert not unpinned, (
        f"in the image's closure but pinned nowhere: {unpinned} — run scripts/lock_constraints.py"
    )


def test_the_venv_holds_nothing_the_image_lacks_except_the_known_dev_only_set():
    resolved = set(lock.closure(lock.requirement_lines(REQUIREMENTS), absent_ok=CI_ABSENT))
    venv = {lock.normalise(d.metadata["Name"]) for d in md.distributions()}
    extra = sorted(venv - resolved - DEV_ONLY)
    assert not extra, (
        f"installed in the venv, absent from the image: {extra}. Tests could pass on a package "
        "production does not have — add it to requirements.txt, or to DEV_ONLY with a reason"
    )


@pytest.mark.parametrize("name", ["mcp", "uvicorn"])
def test_the_mcp_stack_is_pinned_exactly_in_requirements(name):
    assert name in _pins(REQUIREMENTS), f"{name} must be pinned with == in requirements.txt itself"


@pytest.mark.parametrize("name", ["mcp", "uvicorn", "fastapi"])
def test_pyproject_agrees_with_the_effective_pin(name):
    effective = {**_pins(CONSTRAINTS), **_pins(REQUIREMENTS)}[name]
    text = PYPROJECT.read_text()
    match = re.search(rf'^{name}\s*=\s*(?:"([^"]+)"|\{{[^}}]*version\s*=\s*"([^"]+)")', text, re.M)
    assert match, f"{name} is not declared in pyproject.toml"
    assert (match.group(1) or match.group(2)) == effective


def test_the_pins_satisfy_mcps_own_requirement_on_uvicorn():
    """The trap itself: an mcp pin whose uvicorn floor the uvicorn pin does not meet."""
    reqs = [Requirement(r) for r in md.requires("mcp") or []]
    uvicorn = [r for r in reqs if r.name == "uvicorn" and (r.marker is None or r.marker.evaluate())]
    assert uvicorn, "mcp no longer declares uvicorn; revisit this guard"
    pinned = _pins(REQUIREMENTS)["uvicorn"]
    for r in uvicorn:
        assert r.specifier.contains(pinned), (r, pinned)
