"""Write constraints.txt: every package the image installs, at the version the dev venv TESTS.

Ship what is tested (operator decision D31, 2026-10-17). `requirements.txt` names what the
backend depends on directly; anything it leaves as a range, and every transitive dependency,
was resolved by pip at image-build time to whatever was newest — so on 2026-10-17 the image ran
mcp 1.12.4, fastapi 0.143.3 and 24 other versions no test had ever exercised.

This script walks the dependency closure of `requirements.txt` THROUGH THE INSTALLED VENV
(each distribution's own `Requires-Dist`, markers evaluated, extras followed), and writes every
package in it that `requirements.txt` does not already pin with `==`, at its installed version.
The Dockerfile and CI install `-r requirements.txt -c constraints.txt`, so the image resolves
exactly the venv's versions; `tests/unit/test_pinned_versions_match_the_venv.py` fails when the
venv, requirements.txt and constraints.txt disagree.

To change a version: install it in the venv, run the suite, then

    cd backend && venv/bin/python scripts/lock_constraints.py

and commit both files. No network; it reads only the venv.
"""

from __future__ import annotations

import importlib.metadata as md
import re
import sys
from pathlib import Path

from packaging.requirements import Requirement

BACKEND = Path(__file__).resolve().parents[1]
REQUIREMENTS = BACKEND / "requirements.txt"
CONSTRAINTS = BACKEND / "constraints.txt"

HEADER = """\
# GENERATED by scripts/lock_constraints.py — do not edit by hand.
#
# Every package the backend image installs that requirements.txt does not pin with `==`,
# at the exact version the dev venv runs the test suite on (D31, "ship what is tested").
# Installed as `pip install -r requirements.txt -c constraints.txt` by the Dockerfile and CI.
# test_pinned_versions_match_the_venv.py fails when this file, requirements.txt and the venv
# disagree. To move a version: install it in the venv, run the suite, re-run the script.
"""


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def requirement_lines(path: Path) -> list[Requirement]:
    reqs = []
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        reqs.append(Requirement(line))
    return reqs


def applies(req: Requirement, extras: frozenset[str]) -> bool:
    if req.marker is None:
        return True
    return any(req.marker.evaluate({"extra": e}) for e in (extras or {""}))


def closure(roots: list[Requirement], absent_ok: frozenset[str] = frozenset()) -> dict[str, str]:
    """``{normalised name: installed version}`` for every package the roots pull in.

    ``absent_ok`` names roots that may legitimately be missing from this venv (CI's CPU
    runner installs neither triton nor bitsandbytes); any other missing package refuses.
    """
    seen: dict[str, str] = {}
    followed: set[tuple[str, frozenset[str]]] = set()
    queue = [(r, frozenset()) for r in roots if applies(r, frozenset())]
    while queue:
        req, _ = queue.pop()
        name = normalise(req.name)
        extras = frozenset(req.extras)
        if (name, extras) in followed:
            continue
        followed.add((name, extras))
        try:
            dist = md.distribution(req.name)
        except md.PackageNotFoundError:
            if name in absent_ok:
                continue
            raise SystemExit(
                f"{req.name} is in the image's dependency closure but NOT installed in this "
                "venv: install it (and test with it) before locking"
            )
        seen[name] = dist.version
        for spec in dist.requires or []:
            child = Requirement(spec)
            if applies(child, extras):
                queue.append((child, frozenset()))
    return seen


def exact_pins(reqs: list[Requirement]) -> dict[str, str]:
    pins = {}
    for r in reqs:
        specs = list(r.specifier)
        if len(specs) == 1 and specs[0].operator == "==":
            pins[normalise(r.name)] = specs[0].version
    return pins


def render() -> str:
    reqs = requirement_lines(REQUIREMENTS)
    pinned = exact_pins(reqs)
    resolved = closure(reqs)
    body = [f"{name}=={version}" for name, version in sorted(resolved.items()) if name not in pinned]
    return HEADER + "\n".join(body) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if CONSTRAINTS.read_text() == text else 1)
    CONSTRAINTS.write_text(text)
    print(f"wrote {CONSTRAINTS} ({text.count(chr(10)) - HEADER.count(chr(10))} constraints)")
