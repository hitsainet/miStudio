"""The committed export is exactly what census writes (042 FR-042.6; T-06; FTASKS 6.11; CF-1, CF-2).

`docs/legacy-identifiers.md` and `docs/legacy-identifiers.public.md` are GENERATED by the suite's
`specs/ENH-009-rebrand/census.py --export miStudio` (S001 FTDD §4.3) and never edited here. This test
regenerates both from the suite checkout, with the arguments the committed headers record (phase; the
public variant's `forbidden_list: "unread"` means `--public-unchecked`), and requires byte identity.

Ordinary commits here do not churn the files: no record carries `locations` and the header carries the
register's hash, not a commit id (checked below on the committed bytes, without the loader, so the check does
not depend on the loader's own refusal).

Cross-repo: without the suite checkout the regeneration SKIPS LOUDLY; under
`MIWORKBENCH_REQUIRE_CROSS_REPO_CHECKS=1` (or the suite-wide `MISTUDIO_…`) it fails. The full variant does not
exist on the public mirror (the sync keeps only the public file), so its check is skipped there by name.
Controls: K-6.18 (one character of the committed file edited → red), K-6.20 (a `locations` key planted → red),
K-6.19 (churn, green expected: an unrelated commit regenerates the same bytes).
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from tests.support import legacy_export
from tests.support.cross_repo import require_cross_repo
from tests.support.sibling_repos import REPO_ROOT, suite_root

FULL, PUBLIC = legacy_export.paths()


def _census() -> Path:
    return suite_root() / "specs" / "ENH-009-rebrand" / "census.py"


def _python() -> str:
    override = os.environ.get("ENH009_PYTHON")
    if override:
        return override
    venv = Path.home() / ".venvs" / "enh009" / "bin" / "python"
    return str(venv) if venv.exists() else sys.executable


def _skip_or_fail(message: str) -> None:
    if require_cross_repo():
        pytest.fail(message)
    pytest.skip(message)


def _header(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    block = text.split("```jsonl\n", 1)[1]
    return json.loads(block.splitlines()[0])


def _regenerate(committed: Path, public: bool) -> bytes:
    census = _census()
    if not census.is_file():
        _skip_or_fail(f"CROSS-REPO CHECK SKIPPED LOUDLY: the suite's census is not at {census} "
                      "(set MISUITE_REPO to the miSuite checkout)")
    header = _header(committed)
    args = [_python(), str(census), "--export", "miStudio", "--phase", header["phase"]]
    if legacy_export.load(path=committed).pending_ids():
        args.append("--allow-pending")
    if public:
        args.append("--public-unchecked" if header.get("forbidden_list") == "unread" else "--public")
    env = {**os.environ, "MISTUDIO_REPO": str(REPO_ROOT)}
    done = subprocess.run(args, capture_output=True, env=env, timeout=600)
    if done.returncode != 0:
        why = done.stderr.decode(errors="replace")[-600:]
        if "DOCKER_UNAVAILABLE" in why:
            _skip_or_fail(f"CROSS-REPO CHECK SKIPPED LOUDLY: census needs Docker for the public variant: {why}")
        pytest.fail(f"census failed ({done.returncode}): {why}")
    return done.stdout


def _assert_identical(committed: Path, public: bool) -> None:
    fresh = _regenerate(committed, public)
    current = committed.read_bytes()
    if fresh != current:
        import difflib

        diff = "\n".join(list(difflib.unified_diff(current.decode().splitlines(), fresh.decode().splitlines(),
                                                   "committed", "census", lineterm=""))[:40])
        pytest.fail(f"{committed.name} differs from census's output; regenerate it, never edit it:\n{diff}")


def test_full_variant_byte_identical():
    if not FULL.exists():
        if not (REPO_ROOT / "0xcc").is_dir():
            pytest.skip("mirror-shaped tree: the sync keeps only the public export (CF-2)")
        pytest.fail(f"{FULL} is missing in the private repository")
    _assert_identical(FULL, public=False)


def test_public_variant_byte_identical():
    assert PUBLIC.exists(), f"{PUBLIC} is missing: the mirror keeps only that file"
    _assert_identical(PUBLIC, public=True)


def test_no_locations_and_register_hash_header():
    present = [p for p in (FULL, PUBLIC) if p.exists()]
    assert PUBLIC in present
    for path in present:
        lines = [ln for ln in path.read_text(encoding="utf-8").split("```jsonl\n", 1)[1].split("```", 1)[0]
                 .splitlines() if ln.strip()]
        header, records = json.loads(lines[0]), [json.loads(ln) for ln in lines[1:]]
        assert records, path
        assert str(header.get("register_hash", "")).startswith("sha256:"), (path.name, header)
        assert not ({"commit", "source_commit", "generated_at"} & set(header)), (path.name, header)
        carrying = [r.get("id", r.get("old")) for r in records if "locations" in r]
        assert not carrying, f"{path.name}: records carry `locations` (CF-1): {carrying}"
